"""
Cheon's algorithm for the generic-group DLP-with-auxiliary-input challenge.

We are given (in a group G of known prime order N, generator g):
    h   = g^x
    h_d = g^(x^d mod N)      with d | (N-1)

The oracle only lets us build elements of the form g^(c1*E1 + c2*E2 + ...)
for known integers c_i and known exponents E_i (via mul/inv/exp), so any
"discrete-log-with-auxiliary-input" trick must reduce to sequences of such
linear operations plus free label-equality comparisons.

Write N-1 = d*f with gcd(d,f) = 1 (checked at runtime). Let gamma be a
primitive root mod N, zeta = gamma^f (order d), mu = gamma^d (order f).

Step 1 (meet in the middle, cost ~2*sqrt(f)):
    x^d lies in the unique order-f subgroup of Z_N^*, generated by mu, so
    x^d = mu^s (mod N) for some unknown s in [0, f). Since
        h_d = g^(x^d) = g^(mu^s) = g^(mu^(s_a + s_b*m))
            = (g^(mu^s_a)) ^ (mu^(s_b*m))
    we find s via a standard baby-step / giant-step match:
      baby:  B[s_a]  = g^(mu^s_a),                s_a = 0..m-1
      giant: G[s_b]  = h_d^(mu^(-s_b*m)),          s_b = 0..m
    A collision B[s_a] == G[s_b] gives s = s_a + s_b*m.
    Every step is a single "exp by a known scalar" query, chained via
    "$i" back-references inside one batch.

Step 2 (recover a particular d-th root, cost ~d):
    Once s is known, W = x^d mod N = mu^s is an explicit integer. Since
    gcd(d, f) = 1, the d-th power map is a bijection on the order-f
    subgroup, so x0 = W^(d^-1 mod f) mod N is *a* d-th root of W (lying in
    that subgroup). The true x is x0*zeta^i for some unknown i in [0, d):
    scan i = 0..d-1 (chained exp-by-zeta queries) and compare
    g^(x0*zeta^i) against h; a label match gives i, hence x.

Total query cost is about 2*sqrt(f) + d + O(1), far below the sqrt(N)
needed by generic BSGS/Pollard-rho when d is a divisor of N-1 comparable
in size to sqrt(N).
"""
from __future__ import annotations

import math
import sys
from sympy import factorint

from oracle_client import Oracle, OracleError


def extended_gcd(a, b):
    old_r, r = a, b
    old_s, s = 1, 0
    old_t, t = 0, 1
    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
        old_t, t = t, old_t - q * t
    return old_r, old_s, old_t  # gcd, x, y with a*x+b*y=gcd


def modinv(a, m):
    g, x, _ = extended_gcd(a % m, m)
    if g != 1:
        raise ValueError(f"no inverse of {a} mod {m}")
    return x % m


def find_primitive_root(N, factors_of_Nm1):
    M = N - 1
    primes = list(factors_of_Nm1.keys())
    cand = 2
    while True:
        if all(pow(cand, M // q, N) != 1 for q in primes):
            return cand
        cand += 1


def batch_chain(oracle, start_label, scalar, count):
    """Return [start_label, start^scalar, start^(scalar^2), ...] (count+1 items),
    using one HTTP round trip. Costs `count` queries."""
    if count == 0:
        return [start_label]
    ops = []
    for i in range(count):
        prev = "$%d" % (i - 1) if i > 0 else start_label
        ops.append(["exp", prev, str(scalar)])
    results = oracle.query(ops)
    return [start_label] + results


def solve(o: Oracle):
    inst = o.instance
    N = int(inst["N"])
    labels = inst["labels"]
    g, h, h_d = labels["g"], labels["h"], labels["h_d"]
    params = inst.get("params", {})
    d = int(params["d"])

    M = N - 1
    if M % d != 0:
        raise RuntimeError("d does not divide N-1; this attack variant does not apply")
    f = M // d
    g_df, _, _ = extended_gcd(d, f)
    if g_df != 1:
        raise RuntimeError("gcd(d, (N-1)/d) != 1; this attack variant does not apply")

    # Factor N-1 to get a primitive root, and to get mu, zeta of exact orders f, d.
    Nm1_factors = factorint(M)
    gamma = find_primitive_root(N, Nm1_factors)
    mu = pow(gamma, d, N)   # order f
    zeta = pow(gamma, f, N)  # order d

    # ---- Step 1: find s with x^d == mu^s (mod N), via h_d = g^(x^d) ----
    m = math.isqrt(f) + 1

    # baby steps: B[s_a] = g^(mu^s_a), s_a = 0..m-1
    baby_labels = batch_chain(o, g, mu, m - 1)  # length m
    baby_index = {lab: i for i, lab in enumerate(baby_labels)}

    # giant steps: G[s_b] = h_d^(mu^(-s_b*m))
    mu_m = pow(mu, m, N)
    delta = modinv(mu_m, N)  # mu^(-m) mod N
    num_giant = m + 2  # cover full range with a little slack
    giant_labels = batch_chain(o, h_d, delta, num_giant - 1)

    s = None
    for s_b, lab in enumerate(giant_labels):
        if lab in baby_index:
            s_a = baby_index[lab]
            s = s_a + s_b * m
            break
    if s is None:
        raise RuntimeError("no collision found while solving for s (x^d exponent)")

    W = pow(mu, s, N)  # W == x^d mod N, verified via the oracle collision

    # ---- Step 2: particular d-th root of W, then scan the d conjugates ----
    d_inv_f = modinv(d, f)
    x0 = pow(W, d_inv_f, N)

    # Z_i = g^(x0 * zeta^i), i = 0..d-1
    Z0_label = o.exp(g, x0)
    conj_labels = batch_chain(o, Z0_label, zeta, d - 1)  # length d

    i0 = None
    for i, lab in enumerate(conj_labels):
        if lab == h:
            i0 = i
            break
    if i0 is None:
        raise RuntimeError("no match found among the d conjugates; check derivation")

    x = (x0 * pow(zeta, i0, N)) % N

    # sanity check before spending a submit query
    check = o.exp(g, x)
    if check != h:
        raise RuntimeError("sanity check failed: g^x != h")

    return x


def main():
    o = Oracle()
    print(f"[*] instance N={o.instance['N']} d={o.instance.get('params')} "
          f"budget={o.budget} queries_used={o.queries_used}", file=sys.stderr)
    x = solve(o)
    print(f"[*] recovered x = {x}", file=sys.stderr)
    print(f"[*] queries used so far: {o.queries_used}/{o.budget}", file=sys.stderr)
    ok = o.submit(x)
    print(f"[*] submit correct = {ok}", file=sys.stderr)
    print(f"[*] total queries used: {o.queries_used}/{o.budget}", file=sys.stderr)
    if not ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
